async function loadStageData(stage) {
  let query = db.from('piping_joints').select('*');

  if (stage === 'bending_issue') query = query.is('Bend_date', null).is('Issued_for_bending', null);
  else if (stage === 'bend_entry') query = query.is('Bend_date', null).not('Issued_for_bending', 'is', null);
  else if (stage === 'fitup_issue') query = query.not('Bend_date', 'is', null).is('Issue_for_fitup', null);
  else if (stage === 'fitter_name') query = query.not('Issue_for_fitup', 'is', null).is('Fitter_name', null);
  else if (stage === 'ready_fitup') query = query.not('Fitter_name', 'is', null).is('Ready_for_fitup_insp', null);
  else if (stage === 'fitup_entry') query = query.not('Ready_for_fitup_insp', 'is', null).is('Fit_up_date', null);
  else if (stage === 'welder_name') query = query.not('Fit_up_date', 'is', null).is('Welder_no', null);
  else if (stage === 'ready_weld') query = query.not('Welder_no', 'is', null).is('Ready_for_weld_visual', null);
  else if (stage === 'weld_visual') query = query.not('Ready_for_weld_visual', 'is', null).is('Weld_visual_date', null);
  else if (stage === 'ndt_clearance') query = query.not('Weld_visual_date', 'is', null).is('Ndt_clearance', null);
  else if (stage === 'fd') query = query.not('Ndt_clearance', 'is', null).is('Fd_date', null);

  const { data, error } = await query.order('id', { ascending: true }).limit(5000);
  if (error) return alert("Error loading data: " + error.message);

  cumulativeRows = data || [];
  filterBySubStage();
}

function filterBySubStage() {
  if (currentStage === 'ready_fitup') {
    stageFilteredRows = cumulativeRows.filter(r => String(r.Fitter_name || '').trim() === activeSubFilter);
  } else if (currentStage === 'ready_weld') {
    stageFilteredRows = cumulativeRows.filter(r => String(r.Welder_no || '').includes(activeSubFilter));
  } else {
    stageFilteredRows = cumulativeRows;
  }
  applyBalanceFilters();
  updateMetrics();
}

function updateMetrics() {
  const cumSpools = new Set(cumulativeRows.map(r => r.Spool_number).filter(Boolean)).size;
  const cumWelds = calculateWeldSum(cumulativeRows);

  document.getElementById('metricSpools').innerText = cumSpools;
  document.getElementById('metricWelds').innerText = cumWelds;

  if (currentStage === 'ready_fitup' || currentStage === 'ready_weld') {
    const subSpools = new Set(stageFilteredRows.map(r => r.Spool_number).filter(Boolean)).size;
    const subWelds = calculateWeldSum(stageFilteredRows);
    document.getElementById('subMetricSpools').innerText = subSpools;
    document.getElementById('subMetricWelds').innerText = subWelds;
  }
  document.getElementById('tableTotalCount').innerText = activeBalanceDisplayRows.length;
}

function applyBalanceFilters() {
  activeBalanceDisplayRows = stageFilteredRows.filter(r => {
    for (const [colKey, allowedSet] of Object.entries(balanceColumnFilters)) {
      let val = String(r[colKey] !== undefined ? r[colKey] : '').trim();
      const displayVal = val === '' ? '(Blank)' : val;
      if (!allowedSet.has(displayVal)) return false;
    }
    return true;
  });

  document.getElementById('tableTotalCount').innerText = activeBalanceDisplayRows.length;
  renderBalanceTable();
}

function renderBalanceTable() {
  const tbody = document.getElementById('stageBalanceTableBody');
  if (activeBalanceDisplayRows.length === 0) {
    tbody.innerHTML = '<tr><td colspan="5" style="text-align:center; padding:12px; color:#16a34a; font-weight:bold;">🎉 All cleared!</td></tr>';
    return;
  }
  tbody.innerHTML = activeBalanceDisplayRows.slice(0, 500).map(r => `
    <tr>
      <td><b>${r.Drawing_no || '-'}</b></td>
      <td><b>${r.Spool_number || '-'}</b></td>
      <td>${r.Spool_size || '-'}</td>
      <td><b>${r.Weld_id || '-'}</b></td>
      <td>${r.Bend_qty || '-'}</td>
    </tr>
  `).join('');
}

