function bindStageEvents() {
  const searchInput = document.getElementById('spoolSearch');
  const dropdown = document.getElementById('searchDropdown');

  searchInput.addEventListener('input', () => {
    const term = searchInput.value.trim().toLowerCase();
    if (!term) return dropdown.style.display = 'none';

    const matched = stageFilteredRows.filter(r => 
      String(r.Spool_number || '').toLowerCase().includes(term) ||
      String(r.Drawing_no || '').toLowerCase().includes(term) ||
      String(r.Weld_id || '').toLowerCase().includes(term)
    ).slice(0, 35);

    if (matched.length === 0) {
      dropdown.innerHTML = '<div style="padding:10px; color:#94a3b8; font-size:13px; text-align:center;">No Spools Found</div>';
      dropdown.style.display = 'block';
      return;
    }

    dropdown.innerHTML = matched.map(r => `
      <div class="dropdown-row" data-id="${r.id}">
        <div>
          <span style="font-weight: bold; color: #0f172a;">${r.Spool_number || 'N/A'}</span>
          <span style="font-size: 11px; color: #0369a1; margin-left: 6px;">(Size: ${r.Spool_size || '-'}, Weld ID: ${r.Weld_id || '-'})</span>
        </div>
        <span style="color: #475569; font-size: 11.5px;">${r.Drawing_no || '-'}</span>
      </div>
    `).join('');
    dropdown.style.display = 'block';

    dropdown.querySelectorAll('.dropdown-row').forEach(row => {
      row.addEventListener('click', () => onSpoolSelect(parseInt(row.getAttribute('data-id'))));
    });
  });

  document.getElementById('btnAddQueue').addEventListener('click', confirmAddFormToQueue);
  document.getElementById('btnSaveAction').addEventListener('click', submitCurrentStage);
  document.getElementById('btnClearFilters').addEventListener('click', () => {
    balanceColumnFilters = {};
    applyBalanceFilters();
  });

  document.querySelectorAll('.filter-btn-icon').forEach(btn => {
    btn.addEventListener('click', (e) => {
      const colKey = btn.getAttribute('data-key');
      openExcelFilterModal(e, 'balance', colKey, colKey, stageFilteredRows, balanceColumnFilters, applyBalanceFilters);
    });
  });

  document.querySelectorAll('#subFilterArea .sub-filter-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      document.querySelectorAll('#subFilterArea .sub-filter-btn').forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      activeSubFilter = btn.getAttribute('data-val');
      filterBySubStage();
    });
  });
}

function onSpoolSelect(id) {
  if (selectedQueue.some(x => x.id === id)) return alert("⚠️ આ સ્પૂલ પહેલેથી લિસ્ટમાં ઉમેરેલું છે!");
  const item = stageFilteredRows.find(x => x.id === id);
  if (!item) return;

  document.getElementById('spoolSearch').value = '';
  document.getElementById('searchDropdown').style.display = 'none';

  const isDirectStage = ['bending_issue', 'fitup_issue', 'fd', 'ready_fitup', 'fitup_entry', 'ready_weld', 'weld_visual', 'ndt_clearance'].includes(currentStage);
  if (isDirectStage) {
    selectedQueue.push(item);
    document.getElementById('itemEditForm').style.display = 'none';
    renderSelectedTable();
    document.getElementById('spoolSearch').focus();
    return;
  }

  document.getElementById('itemEditForm').style.display = 'block';
  document.getElementById('form_item_id').value = item.id;
  document.getElementById('form_spool_no').value = item.Spool_number || '';
  document.getElementById('form_drawing_no').value = item.Drawing_no || '';

  const dynArea = document.getElementById('dynamicFormFields');
  if (currentStage === 'bend_entry') {
    dynArea.innerHTML = `
      <div><label style="margin-top:0;">BEND QTY:</label><input type="text" id="form_bend_qty" value="${item.Bend_qty || ''}"></div>
      <div><label style="margin-top:0;">WELD ID:</label><input type="text" id="form_weld_id" value="${item.Weld_id || ''}"></div>
    `;
  } else if (currentStage === 'fitter_name') {
    dynArea.innerHTML = `
      <div><label style="margin-top:0;">Select Fitter:</label>
      <select id="form_fitter_val"><option value="">-- Select --</option>${FITTERS.map(f => `<option value="${f}">${f}</option>`).join('')}</select></div>
    `;
  } else if (currentStage === 'welder_name') {
    dynArea.innerHTML = `
      <div><label style="margin-top:0;">Welder 1:</label><select id="form_welder_1"><option value="">-- Select --</option>${WELDERS.map(w => `<option value="${w}">${w}</option>`).join('')}</select></div>
      <div><label style="margin-top:6px;">Welder 2 (Optional):</label><select id="form_welder_2"><option value="">-- None --</option>${WELDERS.map(w => `<option value="${w}">${w}</option>`).join('')}</select></div>
    `;
  }
}

function confirmAddFormToQueue() {
  const id = parseInt(document.getElementById('form_item_id').value);
  const item = stageFilteredRows.find(x => x.id === id);
  if (!item) return;

  let extraData = {};
  if (currentStage === 'bend_entry') {
    extraData.final_bend_qty = document.getElementById('form_bend_qty').value.trim();
    extraData.final_weld_id = document.getElementById('form_weld_id').value.trim();
  } else if (currentStage === 'fitter_name') {
    const val = document.getElementById('form_fitter_val').value;
    if (!val) return alert("કૃપા કરીને Fitter પસંદ કરો!");
    extraData.final_fitter = val;
  } else if (currentStage === 'welder_name') {
    const w1 = document.getElementById('form_welder_1').value;
    const w2 = document.getElementById('form_welder_2').value;
    if (!w1) return alert("કૃપા કરીને Welder 1 પસંદ કરો!");
    extraData.final_welder = (w2 && w2 !== 'NA') ? `${w1}/${w2}` : w1;
  }

  selectedQueue.push({ ...item, ...extraData });
  document.getElementById('itemEditForm').style.display = 'none';
  renderSelectedTable();
  document.getElementById('spoolSearch').focus();
}

async function submitCurrentStage() {
  if (selectedQueue.length === 0) return alert('કૃપા કરીને ઓછામાં ઓછો ૧ Spool સિલેક્ટ કરો.');
  const dateInput = document.getElementById('input_date');
  const enteredDate = dateInput ? dateInput.value : null;

  if (currentStage === 'fitter_name') {
    if (!enteredDate) return alert('કૃપા કરીને Issued to Fitter Date પસંદ કરો.');
    for (const item of selectedQueue) {
      await db.from('piping_joints').update({ Fitter_name: item.final_fitter, issued_to_fitter_date: enteredDate }).eq('id', item.id);
    }
  } else if (currentStage === 'welder_name') {
    if (!enteredDate) return alert('કૃપા કરીને Issued to Welder Date પસંદ કરો.');
    for (const item of selectedQueue) {
      await db.from('piping_joints').update({ Welder_no: item.final_welder, issued_to_welder_date: enteredDate }).eq('id', item.id);
    }
  } else if (currentStage === 'bend_entry') {
    if (!enteredDate) return alert('કૃપા કરીને Bend Date પસંદ કરો.');
    for (const item of selectedQueue) {
      await db.from('piping_joints').update({ Bend_date: enteredDate, Bend_qty: item.final_bend_qty, Weld_id: item.final_weld_id }).eq('id', item.id);
    }
  } else if (currentStage === 'bending_issue') {
    if (!enteredDate) return alert('કૃપા કરીને Bending Issue Date પસંદ કરો.');
    await db.from('piping_joints').update({ Issued_for_bending: enteredDate }).in('id', selectedQueue.map(x => x.id));
  } else if (currentStage === 'fitup_issue') {
    if (!enteredDate) return alert('કૃપા કરીને Fit-Up Issue Date પસંદ કરો.');
    await db.from('piping_joints').update({ Issue_for_fitup: enteredDate }).in('id', selectedQueue.map(x => x.id));
  } else if (currentStage === 'ready_fitup') {
    if (!enteredDate) return alert('કૃપા કરીને Ready Fit-Up Date દાખલ કરો.');
    await db.from('piping_joints').update({ Ready_for_fitup_insp: enteredDate }).in('id', selectedQueue.map(x => x.id));
  } else if (currentStage === 'fitup_entry') {
    if (!enteredDate) return alert('કૃપા કરીને Fit-Up Date પસંદ કરો.');
    await db.from('piping_joints').update({ Fit_up_date: enteredDate }).in('id', selectedQueue.map(x => x.id));
  } else if (currentStage === 'ready_weld') {
    if (!enteredDate) return alert('કૃપા કરીને Ready Weld Date દાખલ કરો.');
    await db.from('piping_joints').update({ Ready_for_weld_visual: enteredDate }).in('id', selectedQueue.map(x => x.id));
  } else if (currentStage === 'weld_visual') {
    if (!enteredDate) return alert('કૃપા કરીને Visual Date દાખલ કરો.');
    await db.from('piping_joints').update({ Weld_visual_date: enteredDate }).in('id', selectedQueue.map(x => x.id));
  } else if (currentStage === 'ndt_clearance') {
    if (!enteredDate) return alert('કૃપા કરીને NDT Clearance Date દાખલ કરો.');
    await db.from('piping_joints').update({ Ndt_clearance: enteredDate }).in('id', selectedQueue.map(x => x.id));
  } else if (currentStage === 'fd') {
    const dcNo = document.getElementById('input_dc_no').value.trim();
    if (!dcNo || !enteredDate) return alert('કૃપા કરીને DC No અને Dispatch Date બંને દાખલ કરો.');
    await db.from('piping_joints').update({ Shift_dc_no: dcNo, Fd_date: enteredDate }).in('id', selectedQueue.map(x => x.id));
  }

  alert(`✅ ${selectedQueue.length} Spools સફળતાપૂર્વક અપડેટ થઈ ગયા!`);
  selectedQueue = [];
  if (document.getElementById('input_date')) document.getElementById('input_date').value = '';
  if (document.getElementById('input_dc_no')) document.getElementById('input_dc_no').value = '';
  if (document.getElementById('spoolSearch')) document.getElementById('spoolSearch').value = '';
  renderSelectedTable();
  await loadStageData(currentStage);
}

function enforcePermissions() {
  const user = getCurrentUser();
  if (!user) return;
  const isAllowed = user.allowed.includes("all") || user.allowed.includes(currentStage);
  if (!isAllowed) {
    document.getElementById('spoolSearch').disabled = true;
    document.getElementById('spoolSearch').placeholder = `🔒 View Only Mode (${user.name})`;
    document.getElementById('btnSaveAction').style.display = 'none';
    document.getElementById('selectedCardArea').style.display = 'none';
  }
}
